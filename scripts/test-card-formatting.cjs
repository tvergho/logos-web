const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const code = ts.transpileModule(fs.readFileSync('lib/utils.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const context={exports:{},process:{env:{}}};vm.runInNewContext(code,context);
const render=context.exports.generateStyledParagraph;
const run={text:'A😀\n<script>&"',underline:false,bold:true,highlight:'cyan'};
const text=run.text;
const card={body:[text],highlights:[],underlines:[],emphasis:[],formatting:{version:2,paragraphs:[{text,runs:[run]}]}};
const out=render(card,0,text);
assert(out.includes('&lt;script&gt;&amp;&quot;'));
assert(out.includes('A😀\n'));
assert(out.includes('font-weight:bold'));
assert(out.includes('background-color:yellow'));
assert(!out.includes('text-decoration:underline'));
assert(!out.includes('<script>'));
assert(render(card,0,text,'aqua').includes('background-color:aqua'));
assert(!render(card,0,text,'red;position:fixed').includes('position:fixed'));
run.bold=false;run.underline=true;
assert(render(card,0,text).includes('text-decoration:underline'));
assert(!render(card,0,text).includes('font-weight:bold'));
run.highlight='red;position:fixed';assert(!render(card,0,text).includes('position:fixed'));
assert.equal(render({...card,formatting:undefined},0,'plain'),'plain');
card.formatting.paragraphs[0].text='mismatch';
assert(!render(card,0,text).includes('text-decoration'));
console.log('Versioned renderer regressions passed');
